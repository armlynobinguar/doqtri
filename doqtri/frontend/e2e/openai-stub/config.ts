/**
 * Where the stand-in OpenAI listens and the key the e2e dev server uses
 * (DOQ-18). playwright.config.ts hands these to both servers and the AI spec
 * reads them, so the three never disagree.
 *
 * None of this is a secret. The key is fake on purpose: if a call ever missed
 * the stub and reached api.openai.com, OpenAI would refuse it with a 401, so a
 * misrouted run fails instead of spending real tokens.
 */

export const OPENAI_STUB_PORT = Number(process.env.E2E_OPENAI_STUB_PORT ?? 4020);

export const OPENAI_STUB_ORIGIN = `http://localhost:${OPENAI_STUB_PORT}`;

/** The SDK's base URL: it appends /responses, /models and so on to this. */
export const OPENAI_STUB_BASE_URL = `${OPENAI_STUB_ORIGIN}/v1`;

export const OPENAI_STUB_API_KEY = "sk-e2e-stub-not-a-real-key";

/**
 * Text that makes the stub fail the AI formatting call, so the upload dialog
 * offers "Import without AI formatting" (MODEL_FAILED).
 */
export const OPENAI_STUB_FAIL_MARKER = "E2E_STUB_FAIL_FORMATTING";

/** The first line the stub adds to every note it formats or regenerates. */
export const OPENAI_STUB_FORMAT_MARK = "Formatted by the e2e OpenAI stub.";
export const OPENAI_STUB_REGENERATE_MARK = "Regenerated by the e2e OpenAI stub.";

/** The root theme of every mindmap the stub builds. */
export const OPENAI_STUB_MINDMAP_THEME = "Stub concept theme";

/** The environment the stub server itself starts with. */
export function openaiStubServerEnv(): Record<string, string> {
  return {
    OPENAI_STUB_PORT: String(OPENAI_STUB_PORT),
    OPENAI_STUB_API_KEY,
    OPENAI_STUB_FAIL_MARKER,
    OPENAI_STUB_FORMAT_MARK,
    OPENAI_STUB_REGENERATE_MARK,
    OPENAI_STUB_MINDMAP_THEME,
  };
}

/**
 * The environment the e2e dev server needs to send every OpenAI call to the
 * stub. The SDK reads OPENAI_BASE_URL when no baseURL is passed, which is how
 * lib/openai.ts, lib/mindmap-ai.ts and lib/promo-rating-ai.ts construct it.
 */
export function openaiStubEnv(): Record<string, string> {
  return {
    OPENAI_BASE_URL: OPENAI_STUB_BASE_URL,
    OPENAI_API_KEY: OPENAI_STUB_API_KEY,
    OPENAI_MODEL: "e2e-stub-model",
  };
}
